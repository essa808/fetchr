"""Convert Lucide SVG icons (ISC licence) into a WPF ResourceDictionary of stroke Geometries.

    python tools/lucide2xaml.py <folder of lucide .svg files> src/Fetchr.App/Themes/Icons.xaml

Get the SVGs from the lucide-static package (pin the version). Keys become Icon.<PascalName>.
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

NUM = re.compile(r"[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?")


def norm(d):
    """Re-space path data so WPF's parser never sees SVG shorthand like "7.54.54"."""
    return " ".join(NUM.findall(d))


def shape(el):
    t = el.tag.split("}")[-1]
    a = el.attrib
    if t == "path":
        tok = NUM.findall(a["d"])
        # The first moveto of an SVG <path> is absolute even when written "m". Once paths are joined
        # into one geometry it would become relative to the previous shape, so make it "M". Extra pairs
        # after "m" are relative line-tos, so they keep their meaning with an explicit "l".
        if tok and tok[0] == "m":
            tok[0] = "M"
            if len(tok) > 3 and not tok[3].isalpha():
                tok.insert(3, "l")
        return " ".join(tok)
    if t == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return f"M {cx - r} {cy} A {r} {r} 0 1 0 {cx + r} {cy} A {r} {r} 0 1 0 {cx - r} {cy} Z"
    if t == "line":
        return f"M {a['x1']} {a['y1']} L {a['x2']} {a['y2']}"
    if t in ("polyline", "polygon"):
        p = NUM.findall(a["points"])
        pts = [f"{p[i]} {p[i + 1]}" for i in range(0, len(p), 2)]
        return "M " + " L ".join(pts) + (" Z" if t == "polygon" else "")
    if t == "rect":
        x, y, w, h = (float(a[k]) for k in ("x", "y", "width", "height"))
        r = float(a.get("rx", 0))
        if not r:
            return f"M {x} {y} H {x + w} V {y + h} H {x} Z"
        return (f"M {x + r} {y} H {x + w - r} A {r} {r} 0 0 1 {x + w} {y + r} V {y + h - r} "
                f"A {r} {r} 0 0 1 {x + w - r} {y + h} H {x + r} A {r} {r} 0 0 1 {x} {y + h - r} "
                f"V {y + r} A {r} {r} 0 0 1 {x + r} {y} Z")
    return ""


def main():
    src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    lines = ["<!-- Lucide icons v0.460.0, ISC licence (https://lucide.dev/license). Generated by tools/lucide2xaml.py. -->",
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
    for svg in sorted(src.glob("*.svg")):
        root = ET.parse(svg).getroot()
        data = " ".join(s for s in (shape(e) for e in root) if s)
        key = "Icon." + "".join(p.capitalize() for p in svg.stem.split("-"))
        lines.append(f'  <Geometry x:Key="{key}">{data}</Geometry>')
    lines.append("</ResourceDictionary>")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("icons:", len(lines) - 4)


if __name__ == "__main__":
    main()
